function shapes(value: string): unknown[] {
  const objects: unknown[] = [
    { v: value },
    { v: [value] },
    { v: { n: value } },
    { [`k${value}`]: 1 },
  ];
  if (value !== "") {
    objects.push(
      { [value]: 1 },
      { v: { [value]: { [value]: value } } },
      { v: [{ [value]: 1 }] },
    );
  } else {
    objects.push({ "": 1 });
  }
  return objects;
}

export function awkward(): unknown[] {
  return [
    ...AWKWARD.flatMap(shapes),
    ...NUMBERS.flatMap((number) => [{ v: number }, { v: [number] }]),
    { v: null },
    { v: true },
    { v: false },
    { v: [] },
    { v: {} },
    { v: [[]] },
    { v: [{}] },
    { v: [[1], [2]] },
    { v: { a: [] } },
    { v: [null] },
    { v: [{ a: null }] },
    { null: 1 },
    { true: 1 },
    { "1": 1 },
    { "1.5": 1 },
    { ["__proto__"]: 1 },
  ];
}

/** mulberry32, so that the values are the same on every run. */
function random(seed: number): (limit: number) => number {
  let state = seed;
  return (limit) => {
    state = (state + 0x6d2b79f5) | 0;
    let t = Math.imul(state ^ (state >>> 15), 1 | state);
    t = (t + Math.imul(t ^ (t >>> 7), 61 | t)) ^ t;
    return ((t ^ (t >>> 14)) >>> 0) % limit;
  };
}

