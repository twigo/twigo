const INDENTS = ["", "", "", "", " ", "  ", "    ", "\t", "  \t"];
const GAPS = [" ", " ", "  ", "\t"];
const TAILS = ["", "", "", "", " ", "\t"];

export const SEED = 8217;
export const COUNT = 8000;

/** Lines long and short, indented or not, joined by line breaks, the shape that the block form and folding get wrong. */
export function generated(seed: number, count: number): unknown[] {
  const next = random(seed);
  const pick = <T>(items: readonly T[]): T => items[next(items.length)] as T;
  const words = (length: number): string => {
    let text = "";
    while (text.length < length) text += pick(WORDS) + pick(GAPS);
    return text;
  };
  const line = (): string => {
    const kind = next(6);
    const body =
      kind === 0 ? "" : kind < 3 ? words(100 + next(120)) : words(5 + next(30));
    return pick(INDENTS) + body.trimEnd() + pick(TAILS);
  };
  return Array.from({ length: count }, (_, index) => {
    const lines = Array.from({ length: 1 + next(6) }, line);
    const text = lines.join("\n") + pick(["", "\n", "\n\n"]);
    const number = next(1_000_000) / (1 + next(1000));
    return index % 2 === 0 ? { v: text, n: number } : { a: { b: [text] } };
  });
}
