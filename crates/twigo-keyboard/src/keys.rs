//! The writing-system keys of the UI Events `KeyboardEvent.code` spec
//! (<https://www.w3.org/TR/uievents-code/#key-alphanumeric-writing-system>)
//! and the native key each platform reports for them: macOS virtual
//! keycodes, XKB keycodes (evdev + 8) and Windows scancodes. The values are
//! Chromium's `dom_code_data.inc`, the table WebView2 maps with, and match
//! WebKit's `codeForKeyEvent` (macOS) and `keyCodeForHardwareKeyCode` (GTK).

macro_rules! keys {
    ($($code:literal mac $mac:literal xkb $xkb:literal win $win:literal,)*) => {
        #[cfg(target_os = "macos")]
        pub(crate) const KEYS: &[(&str, u16)] = &[$(($code, $mac)),*];
        #[cfg(target_os = "linux")]
        pub(crate) const KEYS: &[(&str, u32)] = &[$(($code, $xkb)),*];
        #[cfg(windows)]
        pub(crate) const KEYS: &[(&str, u32)] = &[$(($code, $win)),*];
    };
}

