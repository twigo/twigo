fn main() {
    let commands = tauri_build::AppManifest::new().commands(&[
        "keyboard_layout_watch",
        "shell_environment_watch",
        "shell_environment_retry",
        "contexts_watch",
        "context_mode_set",
        "context_environment_set",
        "context_unlock",
        "context_relock",
        "command_plan",
        "command_execute",
        "command_cancel",
        "apply_preview",
        "access_review",
        "spaces_list",
        "space_open",
        "state_load",
        "state_set",
        "cluster_version",
        "namespaces_list",
        "context_auth_watch",
        "resources_watch",
        "list_subscribe",
        "list_set_window",
        "list_ack",
        "list_unsubscribe",
        "object_open",
        "object_set_parts",
        "object_ack",
        "object_values",
        "object_close",
        "schema_get",
        "logs_open",
        "logs_set_source",
        "logs_set_view",
        "logs_set_window",
        "logs_ack",
        "logs_download",
        "logs_close",
        "shell_containers",
        "shell_open",
        "shell_input",
        "shell_resize",
        "shell_ack",
        "shell_close",
        "terminal_create",
        "kubeconfig_offers_watch",
        "kubeconfig_offer_answer",
        "context_sign_in",
        "context_sign_in_cancel",
        "exec_review",
        "exec_trust",
        "approvals_watch",
        "approval_answer",
        "url_open",
    ]);
    let mut attributes = tauri_build::Attributes::new().app_manifest(commands);
    // An inlined plugin keeps its permissions in OUT_DIR, so builds without the feature have no
    // trace of the bench's commands.
    if std::env::var_os("CARGO_FEATURE_BENCH").is_some() {
        attributes = attributes.plugin(
            "twigo-bench",
            tauri_build::InlinedPlugin::new().commands(&["write", "idle"]),
        );
    }
    tauri_build::try_build(attributes).expect("tauri-build");
}
